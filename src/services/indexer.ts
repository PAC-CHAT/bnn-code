export class CodebaseIndexer {
  private files: Map<string, CodeFile> = new Map();
  private chunks: CodeChunk[] = [];

  constructor() {
    INITIAL_FILES.forEach(f => this.files.set(f.path, f));
    this.index();
  }

  public getFiles(): CodeFile[] {
    return Array.from(this.files.values());
  }

  public getFile(path: string): CodeFile | undefined {
    return this.files.get(path);
  }

  public addOrUpdateFile(file: CodeFile) {
    this.files.set(file.path, file);
    this.index();
  }

  public removeFile(path: string) {
    this.files.delete(path);
    this.index();
  }

  public getChunks(): CodeChunk[] {
    return this.chunks;
  }

  /**
   * AST-aware chunking ported from tree-sitter chunker
   */
  public index(): number {
    this.chunks = [];

    this.files.forEach((file) => {
      const lines = file.content.split('\n');
      let currentChunkLines: string[] = [];
      let startLine = 1;
      let currentSymbol: string | undefined = undefined;
      let currentType: ChunkType = 'other';
      let braceBalance = 0;
      let inBlock = false;

      lines.forEach((line, index) => {
        const lineNum = index + 1;
        const trimmed = line.trim();

        // Detect function or struct or class declaration
        const fnMatch = trimmed.match(/(?:pub\s+)?(?:async\s+)?fn\s+([a-zA-Z0-9_]+)/) ||
                        trimmed.match(/function\s+([a-zA-Z0-9_]+)/) ||
                        trimmed.match(/const\s+([a-zA-Z0-9_]+)\s*=\s*(?:async\s*)?\(/) ||
                        trimmed.match(/def\s+([a-zA-Z0-9_]+)/);

        const structMatch = trimmed.match(/(?:pub\s+)?(?:struct|enum|trait|interface|type|class)\s+([a-zA-Z0-9_]+)/);
        const implMatch = trimmed.match(/(?:pub\s+)?impl(?:\s+<.*>)?\s+([a-zA-Z0-9_]+)/);

        if ((fnMatch || structMatch || implMatch) && !inBlock) {
          if (currentChunkLines.length > 0) {
            this.pushChunk(file.path, currentChunkLines.join('\n'), startLine, lineNum - 1, currentSymbol, currentType);
            currentChunkLines = [];
          }
          startLine = lineNum;
          inBlock = true;
          braceBalance = 0;

          if (fnMatch) {
            currentSymbol = fnMatch[1];
            currentType = 'function';
          } else if (structMatch) {
            currentSymbol = structMatch[1];
            currentType = 'struct';
          } else if (implMatch) {
            currentSymbol = implMatch[1];
            currentType = 'impl';
          }
        }

        currentChunkLines.push(line);

        const opens = (line.match(/{/g) || []).length;
        const closes = (line.match(/}/g) || []).length;
        braceBalance += opens - closes;

        if (inBlock && braceBalance <= 0 && opens > 0) {
          this.pushChunk(file.path, currentChunkLines.join('\n'), startLine, lineNum, currentSymbol, currentType);
          currentChunkLines = [];
          startLine = lineNum + 1;
          inBlock = false;
          currentSymbol = undefined;
          currentType = 'other';
        } else if (currentChunkLines.length >= 35 && !inBlock) {
          this.pushChunk(file.path, currentChunkLines.join('\n'), startLine, lineNum, currentSymbol, currentType);
          currentChunkLines = [];
          startLine = lineNum + 1;
        }
      });

      if (currentChunkLines.length > 0) {
        this.pushChunk(file.path, currentChunkLines.join('\n'), startLine, lines.length, currentSymbol, currentType);
      }
    });

    return this.chunks.length;
  }

  private pushChunk(
    filePath: string,
    content: string,
    startLine: number,
    endLine: number,
    symbolName?: string,
    chunkType: ChunkType = 'other'
  ) {
    if (!content.trim()) return;
    this.chunks.push({
      id: `${filePath}:${startLine}-${endLine}`,
      filePath,
      content,
      startLine,
      endLine,
      symbolName,
      chunkType,
    });
  }

  /**
   * Keyword / FTS Search with ranking
   */
  public search(query: string, topK: number = 3): CodeChunk[] {
    const qTerms = query.toLowerCase().split(/\s+/).filter(t => t.length > 1);
    if (qTerms.length === 0) return this.chunks.slice(0, topK);

    const scored = this.chunks.map(chunk => {
      let score = 0;
      const lowerContent = chunk.content.toLowerCase();
      const lowerPath = chunk.filePath.toLowerCase();
      const lowerSymbol = (chunk.symbolName || '').toLowerCase();

      qTerms.forEach(term => {
        // Exact symbol match is heavily weighted
        if (lowerSymbol === term) score += 50;
        else if (lowerSymbol.includes(term)) score += 20;

        // File path match
        if (lowerPath.includes(term)) score += 15;

        // Content occurrence count
        const occurrences = (lowerContent.match(new RegExp(escapeRegExp(term), 'g')) || []).length;
        score += occurrences * 5;
      });

      return { chunk, score };
    });

    return scored
      .filter(item => item.score > 0)
      .sort((a, b) => b.score - a.score)
      .slice(0, topK)
      .map(item => ({ ...item.chunk, score: item.score }));
  }
}

function escapeRegExp(string: string) {
  return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

